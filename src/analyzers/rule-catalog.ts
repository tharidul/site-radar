export function getRuleDefinition(ruleId: string): RuleDefinition | undefined {
  if (RULE_DEFINITIONS[ruleId]) {
    return RULE_DEFINITIONS[ruleId];
  }

  // Handle dynamic a11y-axe-* rules mapped from axe-core
  if (ruleId.startsWith('a11y-axe-')) {
    const axeId = ruleId.replace('a11y-axe-', '');
    return {
      ruleId,
      category: 'accessibility',
      title: `axe: ${axeId}`,
      description: `Automated WCAG 2.2 AA evaluation discovered violation for rule ${axeId}.`,
      defaultSeverity: 'high',
      weight: 12,
      confidence: 1.0,
      expectedBehavior: `Compliant node structure conforming to axe-core rule ${axeId}.`,
      explanation: `Automated testing flagged accessibility barrier ${axeId}.`,
      recommendation: `Inspect and remediate the node failure identified by axe-core for ${axeId}.`,
      source: 'AxeCoreCollector',
      references: ['https://dequeuniversity.com/rules/axe/'],
    };
  }

  return undefined;
}

export function getAllRules(): RuleDefinition[] {
  return Object.values(RULE_DEFINITIONS);
}
